-- Public catalog and online order requests with stock reservation.
alter table public.inventory
  add column if not exists reserved_quantity integer not null default 0
  check (reserved_quantity >= 0 and reserved_quantity <= quantity);

create table if not exists public.online_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null check (length(trim(customer_name)) between 2 and 160),
  customer_phone text not null check (length(trim(customer_phone)) between 8 and 30),
  delivery_method text not null check (delivery_method in ('delivery','pickup')),
  delivery_address text,
  customer_notes text,
  status text not null default 'pending'
    check (status in ('pending','confirmed','cancelled','fulfilled')),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  idempotency_key uuid not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (delivery_method <> 'delivery' or length(trim(coalesce(delivery_address,''))) >= 5)
);

create table if not exists public.online_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.online_orders(id) on delete restrict,
  variant_id uuid not null references public.product_variants(id) on delete restrict,
  product_name_snapshot text not null,
  size_snapshot text,
  color_snapshot text,
  image_url_snapshot text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists online_orders_status_created_idx
  on public.online_orders(status, created_at desc);
create index if not exists online_orders_phone_created_idx
  on public.online_orders(customer_phone, created_at desc);
create index if not exists online_order_items_order_idx
  on public.online_order_items(order_id);
create index if not exists online_order_items_variant_idx
  on public.online_order_items(variant_id);

alter table public.online_orders enable row level security;
alter table public.online_order_items enable row level security;
revoke all on public.online_orders, public.online_order_items from anon, authenticated;
grant select on public.online_orders, public.online_order_items to authenticated;

drop policy if exists "online orders admin read" on public.online_orders;
create policy "online orders admin read"
  on public.online_orders for select to authenticated
  using ((select public.is_admin()));

drop policy if exists "online order items admin read" on public.online_order_items;
create policy "online order items admin read"
  on public.online_order_items for select to authenticated
  using (exists (
    select 1 from public.online_orders o
    where o.id = online_order_items.order_id
      and (select public.is_admin())
  ));

create or replace function public.get_public_catalog()
returns table (
  product_id uuid,
  product_name text,
  category text,
  sale_price numeric,
  image_url text,
  variant_id uuid,
  size text,
  color text,
  available_quantity integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.id,
    p.name,
    p.category,
    p.sale_price,
    p.image_url,
    v.id,
    v.size,
    v.color,
    greatest(0, coalesce(i.quantity, 0) - coalesce(i.reserved_quantity, 0))
  from public.products p
  join public.product_variants v on v.product_id = p.id
  left join public.inventory i on i.variant_id = v.id
  where p.is_active = true
    and greatest(0, coalesce(i.quantity, 0) - coalesce(i.reserved_quantity, 0)) > 0
  order by p.created_at desc, p.name, v.size, v.color;
$$;

revoke all on function public.get_public_catalog() from public;
grant execute on function public.get_public_catalog() to anon, authenticated;

create or replace function public.create_online_order(
  p_customer_name text,
  p_customer_phone text,
  p_delivery_method text,
  p_delivery_address text,
  p_customer_notes text,
  p_items jsonb,
  p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid;
  v_order_number bigint;
  v_subtotal numeric(12,2) := 0;
  v_item record;
  v_product record;
  v_quantity integer;
  v_available integer;
  v_line_total numeric(12,2);
begin
  if p_idempotency_key is null then
    raise exception 'معرّف الطلب غير صالح';
  end if;

  select id, order_number into v_order_id, v_order_number
  from public.online_orders
  where idempotency_key = p_idempotency_key;

  if v_order_id is not null then
    return jsonb_build_object('id',v_order_id,'order_number',v_order_number,'duplicate',true);
  end if;

  if length(trim(coalesce(p_customer_name,''))) not between 2 and 160 then
    raise exception 'أدخل اسمًا صحيحًا';
  end if;
  if length(regexp_replace(coalesce(p_customer_phone,''),'[^0-9+]','','g')) not between 8 and 16 then
    raise exception 'أدخل رقم هاتف صحيحًا';
  end if;
  if p_delivery_method not in ('delivery','pickup') then
    raise exception 'طريقة الاستلام غير صحيحة';
  end if;
  if p_delivery_method = 'delivery'
     and length(trim(coalesce(p_delivery_address,''))) < 5 then
    raise exception 'عنوان التوصيل مطلوب';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) not between 1 and 20 then
    raise exception 'الطلب يجب أن يحتوي من 1 إلى 20 صنفًا';
  end if;

  -- Lock inventory in deterministic order before checking stock.
  for v_item in
    select
      (entry.value->>'variant_id')::uuid as variant_id,
      sum((entry.value->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) entry(value)
    group by (entry.value->>'variant_id')::uuid
    order by (entry.value->>'variant_id')::uuid
  loop
    if v_item.quantity <= 0 or v_item.quantity > 10 then
      raise exception 'كمية الصنف غير صحيحة';
    end if;
    perform 1 from public.inventory
    where variant_id = v_item.variant_id
    for update;
    if not found then
      raise exception 'الصنف غير متاح حاليًا';
    end if;
  end loop;

  -- Retry after locks: do not reserve twice.
  select id, order_number into v_order_id, v_order_number
  from public.online_orders
  where idempotency_key = p_idempotency_key;
  if v_order_id is not null then
    return jsonb_build_object('id',v_order_id,'order_number',v_order_number,'duplicate',true);
  end if;

  for v_item in
    select
      (entry.value->>'variant_id')::uuid as variant_id,
      sum((entry.value->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) entry(value)
    group by (entry.value->>'variant_id')::uuid
    order by (entry.value->>'variant_id')::uuid
  loop
    select i.quantity - i.reserved_quantity
      into v_available
    from public.inventory i
    where i.variant_id = v_item.variant_id;

    if coalesce(v_available,0) < v_item.quantity then
      raise exception 'الكمية المطلوبة غير متاحة حاليًا';
    end if;
  end loop;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item.value->>'quantity')::integer;
    select p.id,p.name,p.sale_price,p.image_url,v.id,v.size,v.color
      into v_product
    from public.product_variants v
    join public.products p on p.id = v.product_id
    where v.id = (v_item.value->>'variant_id')::uuid
      and p.is_active = true;

    if not found then
      raise exception 'أحد الأصناف لم يعد متاحًا';
    end if;

    v_line_total := round(v_product.sale_price * v_quantity,2);
    v_subtotal := v_subtotal + v_line_total;
  end loop;

  insert into public.online_orders(
    customer_name,customer_phone,delivery_method,delivery_address,
    customer_notes,subtotal,idempotency_key
  )
  values (
    trim(p_customer_name),
    trim(p_customer_phone),
    p_delivery_method,
    nullif(trim(coalesce(p_delivery_address,'')),''),
    nullif(trim(coalesce(p_customer_notes,'')),''),
    v_subtotal,
    p_idempotency_key
  )
  returning id,order_number into v_order_id,v_order_number;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item.value->>'quantity')::integer;
    select p.name,p.sale_price,p.image_url,v.size,v.color
      into v_product
    from public.product_variants v
    join public.products p on p.id = v.product_id
    where v.id = (v_item.value->>'variant_id')::uuid
      and p.is_active = true;

    v_line_total := round(v_product.sale_price * v_quantity,2);

    insert into public.online_order_items(
      order_id,variant_id,product_name_snapshot,size_snapshot,color_snapshot,
      image_url_snapshot,quantity,unit_price,line_total
    )
    values (
      v_order_id,(v_item.value->>'variant_id')::uuid,v_product.name,
      v_product.size,v_product.color,v_product.image_url,v_quantity,
      v_product.sale_price,v_line_total
    );

    update public.inventory
    set reserved_quantity = reserved_quantity + v_quantity,
        updated_at = now()
    where variant_id = (v_item.value->>'variant_id')::uuid;
  end loop;

  return jsonb_build_object('id',v_order_id,'order_number',v_order_number,'subtotal',v_subtotal,'duplicate',false);
end;
$$;

revoke all on function public.create_online_order(text,text,text,text,text,jsonb,uuid) from public;
grant execute on function public.create_online_order(text,text,text,text,text,jsonb,uuid) to anon, authenticated;

create or replace function public.set_online_order_status(
  p_order_id uuid,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.online_orders%rowtype;
  v_item record;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'إدارة طلبات المتجر متاحة للأدمن فقط';
  end if;
  if p_status not in ('confirmed','cancelled','fulfilled') then
    raise exception 'حالة الطلب غير صحيحة';
  end if;

  select * into v_order
  from public.online_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'الطلب غير موجود';
  end if;
  if v_order.status in ('cancelled','fulfilled') then
    raise exception 'لا يمكن تغيير حالة طلب مغلق';
  end if;

  if p_status = 'cancelled' then
    for v_item in
      select variant_id,quantity from public.online_order_items where order_id = p_order_id
    loop
      update public.inventory
      set reserved_quantity = greatest(0,reserved_quantity-v_item.quantity),
          updated_at = now()
      where variant_id = v_item.variant_id;
    end loop;
  elsif p_status = 'fulfilled' then
    if v_order.status <> 'confirmed' then
      raise exception 'يجب تأكيد الطلب قبل تسليمه';
    end if;
    for v_item in
      select variant_id,quantity,product_name_snapshot
      from public.online_order_items
      where order_id = p_order_id
      order by variant_id
    loop
      update public.inventory
      set quantity = quantity - v_item.quantity,
          reserved_quantity = reserved_quantity - v_item.quantity,
          updated_at = now()
      where variant_id = v_item.variant_id
        and quantity >= v_item.quantity
        and reserved_quantity >= v_item.quantity;
      if not found then
        raise exception 'تعذر خصم الكمية المحجوزة؛ راجع المخزون';
      end if;
      insert into public.stock_movements(
        variant_id,movement_type,quantity_delta,reason,reference_id,actor_id
      )
      values (
        v_item.variant_id,'sale',-v_item.quantity,
        'تنفيذ طلب متجر #'||v_order.order_number,p_order_id,auth.uid()
      );
    end loop;
  end if;

  update public.online_orders
  set status = p_status,updated_at = now()
  where id = p_order_id;

  insert into public.audit_logs(actor_id,action,entity_type,entity_id,details)
  values (
    auth.uid(),'set_online_order_status','online_order',p_order_id,
    jsonb_build_object('from',v_order.status,'to',p_status,'order_number',v_order.order_number)
  );

  return jsonb_build_object('id',p_order_id,'order_number',v_order.order_number,'status',p_status);
end;
$$;

revoke all on function public.set_online_order_status(uuid,text) from public,anon;
grant execute on function public.set_online_order_status(uuid,text) to authenticated;
